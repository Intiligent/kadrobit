<?php

namespace App\Enums;

/**
 * What a file is for within an asset.
 */
enum AssetFileRole: string
{
    /** The file uploaded by the user; sent to marketplaces. */
    case Original = 'original';

    /** JPEG copy of a vector (EPS/SVG); marketplaces take them as a pair. */
    case RasterCompanion = 'raster_companion';

    /** Downscaled image for the asset page and AI metadata generation. */
    case Preview = 'preview';

    /** Small image for the library grid; for video — taken from a frame. */
    case Thumbnail = 'thumbnail';

    /** Lightweight video copy for playback in the UI. */
    case VideoPreview = 'video_preview';

    /** Generated by Kadrobit: can be deleted and regenerated. */
    public function isDerived(): bool
    {
        return match ($this) {
            self::Original, self::RasterCompanion => false,
            default => true,
        };
    }

    /**
     * Disk the file lives on: originals on the private bucket, derived files on the public one.
     */
    public function disk(): string
    {
        return config('filesystems.asset_disks.'.($this->isDerived() ? 'public' : 'private'));
    }

    /** Files that are uploaded to marketplaces. */
    public function isUploadable(): bool
    {
        return ! $this->isDerived();
    }
}
