<?php

namespace App\Models;

use App\Enums\AssetFileRole;
use App\Enums\AssetStatus;
use App\Enums\MediaType;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Concerns\HasUlids;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;

/**
 * A stock work (photo, video, vector, illustration) with its base metadata.
 * Physical files live in asset_files; per-marketplace publications in asset_listings.
 *
 * @property int $id
 * @property string $ulid Public identifier for URLs and API
 * @property int $user_id
 * @property int|null $folder_id
 * @property MediaType $type
 * @property AssetStatus $status
 * @property string|null $title
 * @property string|null $description
 * @property array<int, string> $keywords Ordered: the first keywords matter most
 * @property bool $is_editorial
 * @property bool $is_ai_generated
 * @property Carbon|null $captured_at
 * @property array|null $location
 * @property string $original_filename
 * @property string $checksum SHA-256 of the original file
 * @property int|null $width
 * @property int|null $height
 * @property int|null $duration_ms
 * @property array $media_info
 */
class Asset extends Model
{
    use HasUlids, SoftDeletes;

    protected $fillable = [
        'folder_id',
        'type',
        'status',
        'title',
        'description',
        'keywords',
        'is_editorial',
        'is_ai_generated',
        'captured_at',
        'location',
        'original_filename',
        'checksum',
        'width',
        'height',
        'duration_ms',
        'media_info',
    ];

    /** Generated by PostgreSQL, internal to search. */
    protected $hidden = [
        'search',
    ];

    protected $attributes = [
        'status' => 'draft',
        'keywords' => '[]',
        'is_editorial' => false,
        'is_ai_generated' => false,
        'media_info' => '{}',
    ];

    protected function casts(): array
    {
        return [
            'type' => MediaType::class,
            'status' => AssetStatus::class,
            'keywords' => 'array',
            'is_editorial' => 'boolean',
            'is_ai_generated' => 'boolean',
            'captured_at' => 'datetime',
            'location' => 'array',
            'media_info' => 'array',
        ];
    }

    /** Generate a ULID for the "ulid" column; the primary key stays an auto-increment id. */
    public function uniqueIds(): array
    {
        return ['ulid'];
    }

    public function getRouteKeyName(): string
    {
        return 'ulid';
    }

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function folder(): BelongsTo
    {
        return $this->belongsTo(Folder::class);
    }

    public function files(): HasMany
    {
        return $this->hasMany(AssetFile::class);
    }

    public function file(AssetFileRole $role): ?AssetFile
    {
        return $this->relationLoaded('files')
            ? $this->files->firstWhere('role', $role)
            : $this->files()->where('role', $role)->first();
    }

    /** Full-text search over title, keywords and description. */
    public function scopeSearchText(Builder $query, string $terms): void
    {
        $query->whereRaw("search @@ websearch_to_tsquery('english', ?)", [$terms])
            ->orderByRaw("ts_rank(search, websearch_to_tsquery('english', ?)) DESC", [$terms]);
    }

    /** Assets that have all given keywords. */
    public function scopeWithKeywords(Builder $query, array $keywords): void
    {
        $query->whereJsonContains('keywords', array_values($keywords));
    }
}
